        foreach ($pages as $page) {
            $layout = Layouts::where('layout', $page['layout'])->first();

            if (! $layout) {
                $this->command->warn("Skipping '{$page['url']}' — no layout row for {$page['layout']}. Run WebPageLayoutSeeder first.");
                continue;
            }

            unset($page['layout'], $page['parent_url']);
            $page['layout_id'] = $layout->id;

            Templates::updateOrCreate(['url' => $page['url']], $page);
        }

        // Second pass: resolve parent_url to the parent's id.
        $ids = Templates::pluck('id', 'url');

        foreach ($pages as $page) {
            $parentUrl = $page['parent_url'] ?? null;
            $parent = $parentUrl ? ($ids[$parentUrl] ?? 0) : 0;

            Templates::where('url', $page['url'])->update(['parent' => $parent]);
        }
